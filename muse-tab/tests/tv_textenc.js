/* ---------- 编码器：TextDecoder(fatal) 枚举单/双字节反查码表（Node 自带 ICU，无需 iconv-lite） ---------- */
const encCache = {};
function enc(label, s) {
  if (label === 'utf-8') return [...Buffer.from(s, 'utf8')];
  if (!encCache[label]) {
    const td = new TextDecoder(label, { fatal: true }), map = new Map();
    for (let a = 0x80; a <= 0xff; a++) {
      try { const c = td.decode(Uint8Array.of(a)); if (c.length === 1 && !map.has(c)) map.set(c, [a]); } catch (_) {}
      for (let b = 0x40; b <= 0xfe; b++) {
        try { const c = td.decode(Uint8Array.of(a, b)); if (c.length === 1 && !map.has(c)) map.set(c, [a, b]); } catch (_) {}
      }
    }
    encCache[label] = map;
  }
  const out = [];
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (cp < 0x80) { out.push(cp); continue; }
    const b = encCache[label].get(ch); if (!b) throw new Error(label + ' 无法编码 ' + ch);
    out.push(...b);
  }
  return out;
}
